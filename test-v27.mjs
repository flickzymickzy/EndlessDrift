import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {driftStep} from './src/driftPhysics.js';
import {MAX_VEHICLE_SPEED_MPH} from './src/performance.js';
const main=readFileSync('./src/main.js','utf8');
const css=readFileSync('./src/style.css','utf8');
const store=readFileSync('./src/store.js','utf8');
const server=readFileSync('./server.js','utf8');
const html=readFileSync('./index.html','utf8');
assert.equal(MAX_VEHICLE_SPEED_MPH,280);
assert.match(main,/class="beta-label">BETA/);
for(const key of ['ArrowUp','ArrowDown','ArrowLeft','ArrowRight'])assert.match(main,new RegExp(key));
assert.match(main,/touchSize','TOUCH CONTROL SIZE'/);
assert.match(store,/touchSize:100/);
assert.match(css,/--touch-scale/);
assert.match(css,/data-page="leaderboard"/);
assert.match(main,/antialias:document\.documentElement\.dataset\.device==='desktop'/);
assert.match(main,/\?44:document\.documentElement\.dataset\.device==='tablet'\?76:115/);
for(const command of ['boost','slow','resetpowers'])assert.match(server,new RegExp("case '"+command+"'"));
assert.match(main,/\/resetpowers \(restore defaults\)/);
assert.match(server,/ownerRows=featured\.flat\(\)\.filter\(Boolean\)/);
assert.match(server,/const competitive=rows\.filter\(row=>!owners\.has\(row\.username\)\)\.slice\(0,100\)/);
assert.doesNotMatch(server.split("case 'xp':{")[1].split("case 'coins':{")[0],/ed_record_ranked_xp/);
assert.match(html,/src="\.\/src\/main\.js\?v=31"/);
const neutral=driftStep({mph:45,longitudinal:20,lateral:0,steer:0,handbrake:true,dt:1/90});
assert.equal(neutral.lateral,0);
const turn=driftStep({mph:45,longitudinal:20,lateral:0,steer:1,handbrake:true,dt:1/90});
assert.ok(Math.abs(turn.lateral)>0);
assert.ok(Math.abs(turn.yaw)>0);
console.log('V27 mobile, leaderboard, admin, handbrake and 280 MPH speed cap tests passed.');
